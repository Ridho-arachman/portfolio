// One-shot generator: extract every Simple Icons export name from the
// react-icons barrel WITHOUT importing it, and emit a static string list for
// the admin icon picker. Run: `node scripts/generate-si-icon-names.mjs`.
// Rationale: `Object.keys(await import("react-icons/si"))` at runtime defeats
// tree-shaking and drags all ~3.4k icons (~1.9MB gzip) into the public bundle.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const barrel = readFileSync(
  join(root, "node_modules/react-icons/si/index.mjs"),
  "utf8",
);
const names = [
  ...new Set(
    [...barrel.matchAll(/export function (Si[A-Za-z0-9]+)/g)].map((m) => m[1]),
  ),
]
  .filter((name) => name !== "SiIcons")
  .sort();

const out = `// GENERATED by \`node scripts/generate-si-icon-names.mjs\` — do not edit.
// ${names.length} Simple Icons export names as static strings (no react-icons
// import), so the admin picker can enumerate icons without poisoning
// tree-shaking of the barrel in public bundles.
export const SI_ICON_NAMES: readonly string[] = ${JSON.stringify(names)};
`;

writeFileSync(
  join(root, "src/components/sections/admin-skills/si-icon-names.ts"),
  out,
);
console.log(`wrote ${names.length} names`);
